def main() -> None:
    from playwright.sync_api import sync_playwright

    only = set(sys.argv[1:])
    cases = [c for c in CASE_LIST if not only or c.case_id in only]
    launch = {"executable_path": os.environ["CHROMIUM_PATH"]} if os.environ.get("CHROMIUM_PATH") else {}
    with sync_playwright() as p:
        browser = p.chromium.launch(**launch)
        page = browser.new_page()
        for seq, case in enumerate(CASE_LIST, start=101):
            if case not in cases:
                continue
            t = TRADES[case.trade]
            inv = invoice_truth(case, t, seq)
            out = CASES / case.case_id
            out.mkdir(parents=True, exist_ok=True)
            for name, html in [
                ("contract", render(f"contract_{t.template}", contract_values(t, case.date_style))),
                ("invoice", render(f"invoice_{case.invoice_template}", invoice_values(case, t, inv))),
            ]:
                page.set_content(html)
                page.pdf(path=str(out / f"{name}.pdf"), format="A4", prefer_css_page_size=True, print_background=True)
            if case.scanned:
                make_scan(out / "invoice.pdf", case.scanned, seed=case.case_id)
            (out / "expected.json").write_text(
                json.dumps(answer_key(case, t, inv), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
            )
            print(f"{case.case_id}: {case.description}")
        browser.close()
    write_index(CASE_LIST)


if __name__ == "__main__":
    main()

# --- Formatting --------------------------------------------------------------------


def fmt_date(d: date, style: str) -> str:
    return {
        "long": f"{d.day:02d} {d:%B %Y}",
        "us": f"{d:%B} {d.day}, {d.year}",
        "iso": d.isoformat(),
        "dot": d.strftime("%d.%m.%Y"),
        "abbr": d.strftime("%d-%b-%Y"),
    }[style]


def fmt_num(x: float, decimals: int, style: str = "en") -> str:
    text = f"{x:,.{decimals}f}"
    if style == "br":
        text = text.replace(",", "_").replace(".", ",").replace("_", ".")
    return text


def contract_values(t: Trade, date_style: str) -> dict:
    seller, seller_addr = COMPANIES[t.seller]
    buyer, buyer_addr = COMPANIES[t.buyer]
    com = COMMODITIES[t.commodity]
    qty = fmt_num(t.quantity_mt, 0)
    tol = None if t.tolerance is None else fmt_num(t.tolerance, 0)
    price = f"USD {fmt_num(t.unit_price, 2)}"
    if t.template == "a":
        quantity = f"{qty} metric tons, {tol}% more or less at {t.option}'s option." if tol else f"{qty} metric tons."
        price_text = f"{price} per metric ton, {t.incoterm} {PLACES[t.place]}."
    elif t.template == "b":
        molxo = "MOLSO" if t.option == "Seller" else "MOLBO"
        quantity = f"{qty} MT +/- {tol}% {molxo}" if tol else f"{qty} MT"
        price_text = f"{price} PMT"
    else:
        quantity = f"{qty} metric tonnes ({tol}% more or less in {t.option}s' option)" if tol else f"{qty} metric tonnes"
        price_text = f"{price} per metric tonne"
    return {
        "contract_number": t.contract_number,
        "contract_date": fmt_date(t.contract_date, date_style),
        "seller_name": seller, "seller_name_upper": seller.upper(), "seller_address": seller_addr,
        "buyer_name": buyer, "buyer_address": buyer_addr,
        "commodity_short": com["short"], "commodity_desc": com["desc"],
        "quality_rows": "".join(f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in com["rows"]),
        "quality_inline": com["inline"],
        "quantity_text": quantity, "price_text": price_text, "incoterm": t.incoterm,
        "incoterm_text": f"{t.incoterm} {PLACES[t.place]}",
        "shipment_start": fmt_date(t.ship_start, date_style),
        "shipment_end": fmt_date(t.ship_end, date_style),
        "arbitration": com["rules"],
    }


@dataclass
class InvoiceTruth:
    """The invoice's real values, used both to render it and as its answer key."""
    number: str
    date: date
    contract_reference: str
    seller_text: str
    buyer_text: str
    commodity: str
    quantity: float
    unit: str  # "MT" or "BU"
    unit_price: float
    total: float
    incoterm: str
    place: str
    bl_date: date | None


def invoice_truth(case: Case, t: Trade, seq: int) -> InvoiceTruth:
    prefix = {"cerrado": "CVG-INV-2026-", "rioclaro": "RCA/INV/26/", "planura": "PLN-FAT-2026-"}[t.seller]
    price_mt = case.unit_price or t.unit_price
    commodity = case.commodity or t.commodity
    if case.bushels:
        mt_per_bu = MT_PER_BUSHEL[commodity]
        quantity, unit, price = float(round(case.quantity_mt / mt_per_bu)), "BU", round(price_mt * mt_per_bu, 4)
    else:
        quantity, unit, price = case.quantity_mt, "MT", price_mt
    issued = (case.bl_date or t.ship_start + timedelta(days=14)) + timedelta(days=3)
    return InvoiceTruth(
        number=f"{prefix}{seq:04d}",
        date=issued,
        contract_reference=case.contract_reference or t.contract_number,
        seller_text=case.seller_text or COMPANIES[t.seller][0],
        buyer_text=case.buyer_text or COMPANIES[case.buyer or t.buyer][0],
        commodity=commodity,
        quantity=quantity,
        unit=unit,
        unit_price=price,
        total=round(round(quantity * price, 2) + case.total_error, 2),
        incoterm=case.incoterm or t.incoterm,
        place=case.place or t.place,
        bl_date=case.bl_date,
    )



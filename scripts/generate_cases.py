# Scan damage per quality level: resolution, tilt in degrees, speckle (share of
# pixels changed and how much), blur radius, JPEG quality.
SCAN_QUALITY = {
    "good": {"dpi": 200, "tilt": 0.4, "speckle": (1 / 60, 10), "blur": 0.3, "jpeg": 80},
    "fair": {"dpi": 150, "tilt": 1.2, "speckle": (1 / 25, 18), "blur": 0.6, "jpeg": 55},
    "poor": {"dpi": 110, "tilt": 2.0, "speckle": (1 / 12, 28), "blur": 1.0, "jpeg": 35},
}


def make_scan(pdf_path: Path, quality: str, seed: str) -> None:
    """Replace a PDF with an image-only copy that looks scanned. Same seed, same scan."""
    import io
    import random

    import pypdfium2 as pdfium
    from PIL import Image, ImageFilter

    q = SCAN_QUALITY[quality]
    rng = random.Random(seed)
    pages = []
    for page in pdfium.PdfDocument(str(pdf_path)):
        img = page.render(scale=q["dpi"] / 72).to_pil().convert("L")
        img = img.rotate(q["tilt"] * rng.choice((-1, 1)), resample=Image.BICUBIC, expand=True, fillcolor=255)
        share, strength = q["speckle"]
        px, (w, h) = img.load(), img.size
        for _ in range(int(w * h * share)):
            x, y = rng.randrange(w), rng.randrange(h)
            px[x, y] = max(0, min(255, px[x, y] + rng.randint(-strength, strength)))
        img = img.filter(ImageFilter.GaussianBlur(q["blur"]))
        buffer = io.BytesIO()
        img.save(buffer, "JPEG", quality=q["jpeg"])
        buffer.seek(0)
        pages.append(Image.open(buffer).convert("L"))
    pages[0].save(pdf_path, "PDF", resolution=q["dpi"], save_all=True, append_images=pages[1:])


def render(template: str, values: dict) -> str:
    return Template((TEMPLATES / f"{template}.html").read_text(encoding="utf-8")).substitute(values)


